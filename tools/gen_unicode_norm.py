"""Generate Unicode normalization tables for NFKC (spec section 4).

Reads the Unicode data from the running interpreter's unicodedata module
(UCD 15.0.0 on Python 3.12) and writes
native/crates/coil-front/src/parser/unicode_norm.rs with:
  - full NFKD decomposition mappings
  - canonical combining classes
  - canonical composition pairs (Hangul handled algorithmically in Rust)
"""

import sys
import unicodedata
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "native/crates/coil-front/src/parser/unicode_norm.rs"

MAX_CP = 0x10FFFF


def main() -> int:
    decompositions = []
    for cp in range(MAX_CP + 1):
        if 0xAC00 <= cp < 0xAC00 + 11172:
            continue  # Hangul syllables decompose algorithmically
        d = unicodedata.normalize("NFKD", chr(cp))
        if d != chr(cp):
            decompositions.append((cp, [ord(c) for c in d]))

    combining = [cp for cp in range(MAX_CP + 1) if unicodedata.combining(chr(cp)) != 0]

    # Derive every canonical composition pair by simulating the composition
    # pass over the NFD of each codepoint and recording each merge. Merges
    # can be chained (A + diaeresis -> U+00C4, then U+00C4 + macron ->
    # U+01D5), so two-element NFDs alone are not enough. A starter S and mark
    # M merge to C iff NFD(C) equals the source slice they came from, which
    # is how the real algorithm identifies composites; singletons and other
    # composition exclusions fail the NFC round-trip and get no entry.
    # Hangul merges are algorithmic in Rust and are skipped here.
    reverse = {}
    for cp in range(MAX_CP + 1):
        nfd = unicodedata.normalize("NFD", chr(cp))
        if nfd == chr(cp) or len(nfd) < 2:
            continue
        if unicodedata.normalize("NFC", nfd) == chr(cp):
            reverse[tuple(ord(c) for c in nfd)] = cp

    pairs = set()
    for seq in reverse:
        out = []  # merged characters
        spans = []  # source (start, end) slice of each out entry
        last_cc = 0
        for j, ch in enumerate(seq):
            cls = unicodedata.combining(chr(ch))
            if out and (last_cc < cls or last_cc == 0):
                st = out[-1]
                hangul = (0x1100 <= st <= 0x1112 and 0x1161 <= ch <= 0x1175) or (
                    0xAC00 <= st <= 0xD7A3 and (st - 0xAC00) % 28 == 0 and 0x11A8 <= ch <= 0x11C2
                )
                merged = None if hangul else reverse.get(tuple(seq[spans[-1][0] : j + 1]))
                if merged is not None:
                    pairs.add((st, ch, merged))
                    out[-1] = merged
                    spans[-1] = (spans[-1][0], j + 1)
                    continue
            if cls == 0 or not out:
                last_cc = cls
                out.append(ch)
                spans.append((j, j + 1))
                continue
            last_cc = cls
            out.append(ch)
            spans.append((j, j + 1))

    compositions = sorted(pairs)

    lines = []
    lines.append("// Generated by tools/gen_unicode_norm.py. Do not edit.")
    lines.append("//! Unicode 15.0.0 normalization data for NFKC of identifiers.")
    lines.append("")
    lines.append("/// (codepoint, NFKD decomposition) pairs, sorted by codepoint.")
    lines.append("pub static DECOMPOSITIONS: [(u32, &[u32]); %d] = [" % len(decompositions))
    for cp, d in decompositions:
        lines.append("    (0x%X, &[%s])," % (cp, ", ".join("0x%X" % c for c in d)))
    lines.append("];")
    lines.append("")
    lines.append("/// (codepoint, canonical combining class) for ccc != 0, sorted by codepoint.")
    lines.append("pub static COMBINING: [(u32, u8); %d] = [" % len(combining))
    for cp in combining:
        lines.append("    (0x%X, %d)," % (cp, unicodedata.combining(chr(cp))))
    lines.append("];")
    lines.append("")
    lines.append("/// (starter, combining, composed) canonical composition pairs, sorted by")
    lines.append("/// (starter, combining). Hangul composition is algorithmic.")
    lines.append("pub static COMPOSITIONS: [(u32, u32, u32); %d] = [" % len(compositions))
    for first, second, cp in compositions:
        lines.append("    (0x%X, 0x%X, 0x%X)," % (first, second, cp))
    lines.append("];")
    lines.append("")
    OUT.write_text("\n".join(lines))

    # validation: full NFKC on every codepoint must match unicodedata
    sys.path.insert(0, str(OUT.parent))
    print(
        f"decompositions={len(decompositions)} combining={len(combining)} "
        f"compositions={len(compositions)}"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
